import { execFileSync } from "node:child_process";
import { copyFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import esbuild from "esbuild";

// Keep this banner free of any `*/` sequence (including inside words like
// `src/**/`), otherwise it terminates the comment early and the emitted
// bundle becomes syntactically invalid.
const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source code: the src/ directory
*/
`;

const prod = process.argv[2] === "production";

/**
 * `OBSIDIAN_VAULT=/path/to/vault npm run dev` builds straight into that vault's
 * plugin folder and keeps manifest.json and styles.css in sync. Together with
 * the Hot Reload community plugin, every save reloads Notemoji in Obsidian.
 */
const vault = !prod ? process.env.OBSIDIAN_VAULT : undefined;
const outDir = vault ? path.join(vault, ".obsidian", "plugins", "notemoji") : ".";

/** @type {import("esbuild").Plugin} */
const copyPluginFiles = {
	name: "copy-plugin-files",
	setup(build) {
		build.onEnd(async (result) => {
			if (result.errors.length > 0) return;
			await copyFile("manifest.json", path.join(outDir, "manifest.json"));
			await copyFile("styles.css", path.join(outDir, "styles.css"));
			// Picked up by https://github.com/pjeby/hot-reload
			await writeFile(path.join(outDir, ".hotreload"), "");
			console.log(`[notemoji] copied into ${outDir}`);
		});
	},
};

if (vault) await mkdir(outDir, { recursive: true });

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/*",
		"@lezer/*",
		"child_process",
		"crypto",
		"fs",
		"http",
		"https",
		"net",
		"os",
		"path",
		"stream",
		"url",
		"util",
		"zlib",
	],
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: path.join(outDir, "main.js"),
	minify: prod,
	plugins: vault ? [copyPluginFiles] : [],
});

if (prod) {
	await context.rebuild();
	// A bundle that cannot even be parsed can never be loaded by Obsidian, so
	// fail the build instead of shipping it (see the banner comment above).
	execFileSync(process.execPath, ["--check", "main.js"], { stdio: "inherit" });
	process.exit(0);
} else {
	await context.watch();
}
