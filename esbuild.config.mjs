import { execFileSync } from "node:child_process";
import esbuild from "esbuild";
import process from "process";

// Keep this banner free of any `*/` sequence (including inside words like
// `src/**/`), otherwise it terminates the comment early and the emitted
// bundle becomes syntactically invalid.
const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source code: main.ts and the src/ directory
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/*",
		"@lezer/*",
		"child_process",
		"crypto",
		"fs",
		"http",
		"https",
		"net",
		"os",
		"path",
		"stream",
		"url",
		"util",
		"zlib",
	],
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
});

if (prod) {
	await context.rebuild();
	// A bundle that cannot even be parsed can never be loaded by Obsidian, so
	// fail the build instead of shipping it (see the banner comment above).
	execFileSync(process.execPath, ["--check", "main.js"], { stdio: "inherit" });
	process.exit(0);
} else {
	await context.watch();
}
