/**
 * Generates src/icons/emoji-set-previews.ts: a small preview strip for every
 * downloadable emoji set, so the settings can show what a style looks like
 * before it is downloaded.
 *
 * Downloads each pinned font (verifying its checksum), renders sample emoji
 * with it in Chromium and embeds the result as PNG data URLs. Run with
 * `npm run set-previews` after changing src/icons/emoji-sets.ts.
 */
import { Buffer } from "node:buffer";
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";
import { chromium } from "playwright-core";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const cacheDir = path.join(root, ".test-build", "fonts");
const outFile = path.join(root, "src", "icons", "emoji-set-previews.ts");

/** The emoji shown in every preview. */
export const SAMPLE = "😀 🚀 📁 🎨 🏠 ✅ 💡 🔥".split(" ");

async function loadSets() {
	const result = await build({
		entryPoints: [path.join(root, "src", "icons", "emoji-sets.ts")],
		bundle: true,
		write: false,
		format: "esm",
		logLevel: "warning",
	});
	const url = `data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString("base64")}`;
	return (await import(url)).EMOJI_SETS;
}

async function fetchFont(set) {
	const file = path.join(cacheDir, set.file);
	let data = await readFile(file).catch(() => null);
	if (!data) {
		const response = await fetch(set.url);
		if (!response.ok) throw new Error(`${set.name}: HTTP ${response.status}`);
		data = Buffer.from(await response.arrayBuffer());
		await writeFile(file, data);
	}
	const hash = createHash("sha256").update(data).digest("hex");
	if (hash !== set.sha256) throw new Error(`${set.name}: checksum mismatch (${hash})`);
	return file;
}

await mkdir(cacheDir, { recursive: true });
const sets = await loadSets();
const fonts = await Promise.all(sets.map(fetchFont));

const html = `<!doctype html><meta charset="utf-8"><style>
body { margin: 0; background: transparent; }
${sets.map((set, i) => `@font-face { font-family: "set-${set.id}"; src: url("${pathToFileURL(fonts[i]).href}"); }`).join("\n")}
.strip { display: inline-flex; gap: 6px; padding: 2px; font-size: 20px; line-height: 1; color: #fff; }
</style>
${sets.map((set) => `<div><span class="strip" id="${set.id}" style="font-family: 'set-${set.id}'">${SAMPLE.map((emoji) => `<span>${emoji}</span>`).join("")}</span></div>`).join("\n")}`;
const htmlFile = path.join(cacheDir, "previews.html");
await writeFile(htmlFile, html);

const browser = await chromium.launch();
const previews = {};
try {
	const page = await browser.newPage({ deviceScaleFactor: 2 });
	await page.goto(pathToFileURL(htmlFile).href);
	await page.evaluate(() => document.fonts.ready);
	for (const set of sets) {
		const png = await page.locator(`#${set.id}`).screenshot({ omitBackground: true });
		previews[set.id] = `data:image/png;base64,${png.toString("base64")}`;
		console.log(`${set.name}: ${(png.length / 1024).toFixed(1)} KB`);
	}
} finally {
	await browser.close();
}

const source = `// Generated by scripts/generate-set-previews.mjs from the pinned fonts in emoji-sets.ts.
// Do not edit by hand; run \`npm run set-previews\` instead.
//
// Preview strips (PNG, rendered with each set's own font) of: ${SAMPLE.join(" ")}

export const EMOJI_SET_PREVIEWS: Readonly<Record<string, string>> = {
${Object.entries(previews)
	.map(([id, url]) => `\t${JSON.stringify(id)}: ${JSON.stringify(url)},`)
	.join("\n")}
};

/** The sample emoji, for previews rendered live (system emoji, own font). */
export const PREVIEW_SAMPLE = ${JSON.stringify(SAMPLE.join(""))};
`;
await writeFile(outFile, source, "utf8");
console.log(`Wrote ${path.relative(root, outFile)}`);
