/**
 * Generates `src/picker/emoji-data.ts` from the `emojibase-data` package.
 *
 * The output is committed so that building the plugin needs no network and no
 * extra runtime dependency. Run `npm run emoji-data` after upgrading
 * `emojibase-data` or changing the settings below.
 */
import { createRequire } from "node:module";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(root, "src", "picker", "emoji-data.ts");

/**
 * Newest Emoji version to include. Newer emoji render as empty boxes on many
 * systems (older Windows/Android), which is a bad first impression in a picker.
 * Any emoji can still be pasted or typed into the search field.
 */
const MAX_EMOJI_VERSION = 15;

/** Picker categories in display order, mapped from emojibase group ids. */
const CATEGORIES = [
	{ id: "smileys", label: "Smileys & emotion", icon: "😀", group: 0 },
	{ id: "people", label: "People & body", icon: "👋", group: 1 },
	{ id: "nature", label: "Animals & nature", icon: "🐻", group: 3 },
	{ id: "food", label: "Food & drink", icon: "🍔", group: 4 },
	{ id: "travel", label: "Travel & places", icon: "✈️", group: 5 },
	{ id: "activities", label: "Activities", icon: "⚽", group: 6 },
	{ id: "objects", label: "Objects", icon: "💡", group: 7 },
	{ id: "symbols", label: "Symbols", icon: "🔣", group: 8 },
	{ id: "flags", label: "Flags", icon: "🏁", group: 9 },
];

const emojis = require("emojibase-data/en/data.json");
const shortcodes = require("emojibase-data/en/shortcodes/github.json");
const { version } = require("emojibase-data/package.json");

/** Fields must never contain the separators used by the compact format. */
function clean(text) {
	return text
		.toLowerCase()
		.replace(/[|;\n]/g, " ")
		.replace(/\s+/g, " ")
		.trim();
}

function keywordsOf(entry) {
	const words = new Set();
	for (const tag of entry.tags ?? []) words.add(clean(tag));
	const codes = shortcodes[entry.hexcode];
	for (const code of Array.isArray(codes) ? codes : codes ? [codes] : []) {
		words.add(clean(code.replace(/_/g, " ")));
	}
	if (entry.emoticon) {
		for (const emoticon of [].concat(entry.emoticon)) words.add(clean(emoticon));
	}
	words.delete(clean(entry.label));
	words.delete("");
	return [...words].join(";");
}

const output = CATEGORIES.map((category) => {
	const rows = emojis
		.filter((entry) => entry.group === category.group && entry.version <= MAX_EMOJI_VERSION)
		.sort((a, b) => a.order - b.order)
		.map((entry) => [entry.emoji, clean(entry.label), keywordsOf(entry)].join("|"));
	return { id: category.id, label: category.label, icon: category.icon, rows };
});

const total = output.reduce((sum, category) => sum + category.rows.length, 0);

const source = `// Generated by scripts/generate-emoji-data.mjs from emojibase-data ${version}.
// Do not edit by hand; run \`npm run emoji-data\` instead.
//
// Each row is \`emoji|name|keyword;keyword\`.

export interface RawEmojiCategory {
	id: string;
	label: string;
	icon: string;
	rows: string;
}

export const RAW_EMOJI_CATEGORIES: RawEmojiCategory[] = [
${output
	.map(
		(category) =>
			`\t{\n\t\tid: ${JSON.stringify(category.id)},\n\t\tlabel: ${JSON.stringify(category.label)},\n\t\ticon: ${JSON.stringify(category.icon)},\n\t\trows: ${JSON.stringify(category.rows.join("\n"))},\n\t},`,
	)
	.join("\n")}
];
`;

await writeFile(outFile, source, "utf8");
console.log(
	`Wrote ${total} emoji in ${output.length} categories to ${path.relative(root, outFile)}`,
);
